/**
 * 日本語検索用のローカル銘柄辞書。
 *
 * グローバル版 Yahoo の検索APIは日本語クエリにほぼ対応していないため、
 * 主要銘柄はアプリ内の辞書で照合する（Yahoo検索とマージして使う）。
 * keywords にはひらがな・略称・ローマ字などの別名を入れる。
 */
object SearchDictionary {

    data class Entry(
        val symbol: String,
        val name: String,
        val exchange: String,
        val keywords: List<String>,
    )

    fun search(query: String): List<StockSearchResult> {
        val q = normalize(query)
        if (q.isBlank()) return emptyList()
        return entries
            .filter { entry ->
                normalize(entry.name).contains(q) ||
                    entry.symbol.lowercase().startsWith(q) ||
                    entry.symbol.substringBefore(".").lowercase() == q ||
                    entry.keywords.any { normalize(it).contains(q) }
            }
            .sortedByDescending { normalize(it.name).startsWith(q) }
            .take(30)
            .map { StockSearchResult(it.symbol, it.name, it.exchange) }
    }

    /** 小文字化・カタカナ→ひらがな・空白と中点の除去 */
    private fun normalize(text: String): String = buildString(text.length) {
        for (ch in text.lowercase().trim()) {
            when {
                ch == ' ' || ch == '　' || ch == '・' || ch == '-' -> Unit
                ch in 'ァ'..'ヶ' -> append(ch - 0x60) // カタカナ→ひらがな
                else -> append(ch)
            }
        }
    }

    private fun jp(code: String, name: String, vararg keywords: String) =
        Entry("$code.T", name, "東証", keywords.toList())

    private fun us(symbol: String, name: String, vararg keywords: String) =
        Entry(symbol, name, "米国", keywords.toList())

    private fun ix(symbol: String, name: String, vararg keywords: String) =
        Entry(symbol, name, "指数", keywords.toList())

    private fun fx(symbol: String, name: String, vararg keywords: String) =
        Entry(symbol, name, "FX", keywords.toList())

